_C1 = L.load("C1")


def _lab_rows():
    """C1 の境目ごとの「実際の状態」（行の行き先から判定）を表の行にする"""
    if not _C1:
        return [["（未実施）", "", "", "", ""]]
    rows = []
    for b in _C1["boundaries"]:
        mk = None
        for k in _C1["fates"]:
            if k.endswith(b["boundary_utc"][:5].replace(":", "-")):
                mk = k
        if not mk:
            continue
        f = _C1["fates"][mk]
        cnt = {}
        for v in f.values():
            cnt[v] = cnt.get(v, 0) + 1
        cur = [t for t, v in f.items() if v == "CURRENT"]
        rows.append([
            "%s（UTC）" % b["boundary_utc"],
            " → ".join(b["order"]),
            "%d" % cnt.get("CURRENT", 0),
            "%d" % cnt.get("ARCHIVE", 0),
            "%d" % cnt.get("STALE", 0),
            "、".join(cur) + "（順番の最後: %s）" % b["order"][-1],
        ])
    return rows


def _lab_line():
    if not _C1:
        return "（再現実験は未実施）"
    t = L.totals(_C1)
    allb = [b for run in (1, 2, 3) for b in L.boundary_rows(L.load("C1", run=run))]
    one = sum(1 for b in allb if b["cur"] == [b["last"]])
    return ("再現実験 C1（6 タスク・1 分ごとのロールオーバ・EFS と同じく「消された実体に Stale を返す」NFS サーバ）を 3 回行い、"
            "%d 回の境目のうち %d 回で、正しく書けたのは「その分の最後にロールオーバしたタスク」1 つだけだった。"
            "本番と同じ配置の 3 回目では、書いた %d 行のうち、正しいファイルに残ったのは %d 行（%s）、別の時間帯のファイルに入ったのが %d 行（%s）、"
            "消えたのが %d 行（%s）。"
            % (len(allb), one, t["emitted"], t["ok"], t["ok_p"], t["mis"], t["mis_p"], t["lost"], t["lost_p"]))


